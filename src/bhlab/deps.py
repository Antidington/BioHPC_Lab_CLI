from __future__ import annotations

from pathlib import Path

from bhlab.capabilities import Capabilities, Library, detect


def probe() -> dict[str, Library]:
    return detect().libraries


def load_profile(root: Path, name: str) -> dict:
    path = root / "platforms" / f"{name}.toml"
    if not path.exists():
        raise FileNotFoundError(
            f"platform profile not found: {path}. Choose local-clang, cpu-gcc, or gpu-cuda."
        )
    try:
        import tomllib
    except ModuleNotFoundError:  # pragma: no cover - Python 3.10
        import tomli as tomllib

    with path.open("rb") as handle:
        return tomllib.load(handle)


def config_mk(caps: Capabilities, profile: dict) -> str:
    libraries = caps.libraries
    cflags = [library.cflags for library in libraries.values() if library.found and library.cflags]
    libs = [library.libs for library in libraries.values() if library.found and library.libs]
    if caps.cuda:
        libs.append("-lcudart")
    have_mpi = 1 if (caps.mpi and profile.get("mpi", True)) else 0
    have_charm = 1 if (caps.charm and profile.get("charm", True)) else 0
    have_cuda = 1 if (caps.cuda and profile.get("cuda", False)) else 0
    have_openmp = 1 if (caps.openmp and profile.get("openmp", False)) else 0
    have_zlib = 1 if libraries.get("zlib") and libraries["zlib"].found else 0
    lines = [
        "# Generated by bhlab. Edit platforms/*.toml or bhlab.toml instead.",
        f"BHLAB_PLATFORM := {profile.get('name', 'unknown')}",
        f"HAVE_MPI := {have_mpi}",
        f"HAVE_CHARM := {have_charm}",
        f"HAVE_CUDA := {have_cuda}",
        f"HAVE_OPENMP := {have_openmp}",
        f"HAVE_ZLIB := {have_zlib}",
        f"BHLAB_LIBS := {' '.join(libs)}",
        f"BHLAB_CFLAGS := {' '.join(cflags + profile.get('cflags', []))}",
        f"BHLAB_LDFLAGS := {' '.join(profile.get('ldflags', []))}",
        f"CXX := {profile.get('cxx', 'c++')}",
        f"MPICXX := {profile.get('mpicxx', 'mpicxx')}",
        f"CHARM_C := {profile.get('charmc', 'charmc')}",
        f"NVCC := {profile.get('nvcc', 'nvcc')}",
        f"CUDA_ARCH := {profile.get('cuda_arch', 'sm_80')}",
    ]
    return "\n".join(lines) + "\n"


MAKEFILE_TEMPLATE = r"""# Generated by bhlab for platform @@PLATFORM@@.
include build/config.@@PLATFORM@@.mk

CXXFLAGS := @@CXXFLAGS@@ -I native/include -MMD -MP $(BHLAB_CFLAGS)
LDFLAGS := @@LDFLAGS@@
LIBS := $(BHLAB_LIBS)
BINDIR := build/bin
OBJROOT := build/obj/@@PLATFORM@@
LOCAL_OBJ := $(OBJROOT)/local
MPI_OBJ := $(OBJROOT)/mpi
LOCAL_DEFS := -DBHLAB_HAVE_ZLIB=$(HAVE_ZLIB)
MPI_DEFS := $(LOCAL_DEFS) -DBHLAB_HAVE_MPI=1

CORE_SRCS := native/src/layout.cpp native/src/kmer.cpp native/src/minimizer.cpp \
             native/src/events.cpp native/src/args.cpp native/src/pipeline.cpp
LOCAL_CORE_OBJS := $(patsubst native/src/%.cpp,$(LOCAL_OBJ)/%.o,$(CORE_SRCS)) \
                   $(LOCAL_OBJ)/comm/mpi_driver.o
MPI_CORE_OBJS := $(patsubst native/src/%.cpp,$(MPI_OBJ)/%.o,$(CORE_SRCS)) \
                 $(MPI_OBJ)/comm/mpi_driver.o

ifeq ($(HAVE_CUDA),1)
CORE_DEFS_EXTRA := -DBHLAB_HAVE_CUDA=1
CUDA_OBJ := $(LOCAL_OBJ)/device/cuda_kernel.o
LOCAL_CORE_OBJS += $(CUDA_OBJ)
CXXFLAGS += -DBHLAB_HAVE_CUDA=1
endif

DEPS := $(shell find $(OBJROOT) -name '*.d' 2>/dev/null)

GEN_LOCAL := $(wildcard build/gen/*_local.cpp)
GEN_MPI := $(wildcard build/gen/*_mpi.cpp)
GEN_CHARM := $(wildcard build/gen/*_charm.cpp)
GEN_LOCAL_BINS := $(patsubst build/gen/%_local.cpp,$(BINDIR)/%,$(GEN_LOCAL))
GEN_MPI_BINS := $(patsubst build/gen/%.cpp,$(BINDIR)/%,$(GEN_MPI))
GEN_CHARM_BINS := $(patsubst build/gen/%.cpp,$(BINDIR)/%,$(GEN_CHARM))

.PHONY: all local mpi charm check clean
all: local
local: $(BINDIR)/bhlab-kmer $(BINDIR)/bhlab-minimizer $(GEN_LOCAL_BINS)

$(BINDIR)/bhlab-kmer: $(LOCAL_OBJ)/apps/kmer_main.o $(LOCAL_CORE_OBJS)
	@mkdir -p $(BINDIR)
	$(CXX) $(CXXFLAGS) $^ -o $@ $(LDFLAGS) $(LIBS)

$(BINDIR)/bhlab-minimizer: $(LOCAL_OBJ)/apps/minimizer_main.o $(LOCAL_CORE_OBJS)
	@mkdir -p $(BINDIR)
	$(CXX) $(CXXFLAGS) $^ -o $@ $(LDFLAGS) $(LIBS)

$(LOCAL_OBJ)/%.o: native/src/%.cpp
	@mkdir -p $(dir $@)
	$(CXX) $(CXXFLAGS) $(LOCAL_DEFS) -c $< -o $@

$(LOCAL_OBJ)/apps/%.o: native/apps/%.cpp
	@mkdir -p $(dir $@)
	$(CXX) $(CXXFLAGS) $(LOCAL_DEFS) -c $< -o $@

$(LOCAL_OBJ)/device/%.o: native/src/device/%.cu
	@mkdir -p $(dir $@)
	$(NVCC) -std=c++17 -O3 -I native/include -MMD -MP -arch=$(CUDA_ARCH) $(LOCAL_DEFS) -c $< -o $@

$(BINDIR)/%: build/gen/%_local.cpp $(LOCAL_CORE_OBJS)
	@mkdir -p $(BINDIR)
	$(CXX) $(CXXFLAGS) $< $(LOCAL_CORE_OBJS) -o $@ $(LDFLAGS) $(LIBS)

ifeq ($(HAVE_MPI),1)
mpi: $(BINDIR)/bhlab-kmer-mpi $(GEN_MPI_BINS)
all: mpi

$(MPI_OBJ)/%.o: native/src/%.cpp
	@mkdir -p $(dir $@)
	$(MPICXX) $(CXXFLAGS) $(MPI_DEFS) -c $< -o $@

$(MPI_OBJ)/apps/%.o: native/apps/%.cpp
	@mkdir -p $(dir $@)
	$(MPICXX) $(CXXFLAGS) $(MPI_DEFS) -c $< -o $@

$(BINDIR)/bhlab-kmer-mpi: $(MPI_OBJ)/apps/kmer_mpi_main.o $(MPI_CORE_OBJS)
	@mkdir -p $(BINDIR)
	$(MPICXX) $(CXXFLAGS) $^ -o $@ $(LDFLAGS) $(LIBS)

$(BINDIR)/%_mpi: build/gen/%_mpi.cpp $(MPI_CORE_OBJS)
	@mkdir -p $(BINDIR)
	$(MPICXX) $(CXXFLAGS) $(MPI_DEFS) $< $(MPI_CORE_OBJS) -o $@ $(LDFLAGS) $(LIBS)
endif

ifeq ($(HAVE_CHARM),1)
charm: $(BINDIR)/bhlab-kmer-charm $(GEN_CHARM_BINS)

$(BINDIR)/bhlab-kmer-charm: native/src/comm/charm_driver.cpp native/src/comm/charm_driver.ci $(CORE_SRCS)
	@mkdir -p $(BINDIR)
	$(CHARM_C) -c++-option -std=c++17 -o $@ native/src/comm/charm_driver.ci native/src/comm/charm_driver.cpp \
	  $(CORE_SRCS) -I . -I native/include -I native/src/comm $(LOCAL_DEFS) $(LIBS) $(LDFLAGS)

$(BINDIR)/%_charm: build/gen/%_charm.cpp build/gen/%_charm.ci $(CORE_SRCS)
	@mkdir -p $(BINDIR)
	$(CHARM_C) -c++-option -std=c++17 -o $@ build/gen/$*_charm.ci build/gen/$*_charm.cpp \
	  $(CORE_SRCS) -I . -I build/gen -I native/include $(LOCAL_DEFS) $(LIBS) $(LDFLAGS)
endif

$(BINDIR)/bhlab-core-test: native/tests/test_core.cpp $(LOCAL_CORE_OBJS)
	@mkdir -p $(BINDIR)
	$(CXX) $(CXXFLAGS) $< $(LOCAL_CORE_OBJS) -o $@ $(LDFLAGS) $(LIBS)

check: $(BINDIR)/bhlab-core-test
	$(BINDIR)/bhlab-core-test

clean:
	rm -rf build/obj/@@PLATFORM@@ build/bin

-include $(DEPS)
"""


def render_makefile(profile: dict, caps: Capabilities) -> str:
    cxxflags = " ".join(profile.get("cxxflags", ["-std=c++17", "-O2"]))
    ldflags = " ".join(profile.get("ldflags", []))
    return (
        MAKEFILE_TEMPLATE.replace("@@PLATFORM@@", profile.get("name", "unknown"))
        .replace("@@CXXFLAGS@@", cxxflags)
        .replace("@@LDFLAGS@@", ldflags)
    )
